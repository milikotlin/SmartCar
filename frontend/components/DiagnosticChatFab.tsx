"use client";

import { useEffect, useRef, useState, type FormEvent } from "react";
import { askChat } from "@/lib/api";
import type { ChatAnswer } from "@/lib/types";

interface Message {
  role: "user" | "assistant";
  text: string;
  meta?: ChatAnswer;
}

interface Props {
  plate: string | null;
  odometerKm: number | null;
}

export function DiagnosticChatFab({ plate, odometerKm }: Props) {
  const [open, setOpen] = useState(false);
  const [messages, setMessages] = useState<Message[]>([]);
  const [draft, setDraft] = useState("");
  const [busy, setBusy] = useState(false);
  const endRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    setMessages([]);
  }, [plate]);
  useEffect(() => {
    endRef.current?.scrollIntoView({ behavior: "smooth" });
  }, [messages, open]);

  async function send(e: FormEvent) {
    e.preventDefault();
    const text = draft.trim();
    if (!text || !plate || busy) return;
    setDraft("");
    setMessages((m) => [...m, { role: "user", text }]);
    setBusy(true);
    try {
      const res = await askChat(plate, text, odometerKm);
      setMessages((m) => [...m, { role: "assistant", text: res.answer, meta: res }]);
    } catch {
      setMessages((m) => [...m, { role: "assistant", text: "The assistant could not be reached. Please try again." }]);
    } finally {
      setBusy(false);
    }
  }

  return (
    <div className="fixed bottom-7 right-7 z-20 flex flex-col items-end gap-3">
      {open && (
        <div className="card-shadow flex h-[480px] w-[min(380px,calc(100vw-2rem))] flex-col overflow-hidden rounded-[14px] border border-line bg-surface" role="dialog" aria-label="AI diagnostic assistant">
          <div className="border-b border-line px-4 py-3">
            <p className="text-[14px] font-semibold text-ink">AI Diagnostics</p>
            <p className="text-[11.5px] text-ink-soft">
              {plate ? `Answers use only the data of plate ${plate}. Not a substitute for a mechanic.` : "Look up a vehicle first."}
            </p>
          </div>
          <div className="flex-1 space-y-3 overflow-y-auto px-4 py-3 text-[13px]">
            {messages.length === 0 && plate && <p className="text-ink-soft">Describe a symptom, e.g. &quot;Hearing a squeaking noise when braking&quot;.</p>}
            {messages.map((m, i) => (
              <div key={i} className={m.role === "user" ? "text-right" : ""}>
                <p className={`inline-block max-w-[92%] whitespace-pre-wrap rounded-[10px] px-3 py-2 text-left ${m.role === "user" ? "bg-accent text-accent-ink" : "bg-paper text-ink"}`}>{m.text}</p>
                {m.meta && (
                  <details className="mt-1 text-[11px] text-ink-faint">
                    <summary className="cursor-pointer">{m.meta.source === "openai" ? `Generated by ${m.meta.model}` : "Rule-based answer (language model not used)"} · data used</summary>
                    <ul className="mt-1 list-disc pl-4">{m.meta.context.map((c) => <li key={c}>{c}</li>)}</ul>
                    {m.meta.note && <p className="mt-1">Note: {m.meta.note}</p>}
                  </details>
                )}
              </div>
            ))}
            {busy && <p className="text-ink-faint">Thinking…</p>}
            <div ref={endRef} />
          </div>
          <form onSubmit={send} className="flex gap-2 border-t border-line p-3">
            <input
              value={draft}
              onChange={(e) => setDraft(e.target.value)}
              disabled={!plate}
              maxLength={1000}
              placeholder="Describe the symptom…"
              aria-label="Describe a symptom"
              className="w-full rounded-md border border-line-strong bg-paper px-3 py-2 text-[13px] text-ink outline-none focus:border-accent"
            />
            <button type="submit" disabled={!plate || busy} className="rounded-md bg-accent px-3 py-2 text-[13px] font-semibold text-accent-ink disabled:opacity-60">Send</button>
          </form>
        </div>
      )}
      <button
        type="button"
        onClick={() => setOpen((o) => !o)}
        aria-label={open ? "Close the AI diagnostic assistant" : "Open the AI diagnostic assistant"}
        aria-expanded={open}
        className="card-shadow flex h-[52px] w-[52px] items-center justify-center rounded-full bg-accent text-accent-ink transition-[filter] hover:brightness-110"
      >
        <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={2} strokeLinecap="round" strokeLinejoin="round" className="h-[22px] w-[22px]">
          <path d="M21 11.5a8.38 8.38 0 0 1-.9 3.8 8.5 8.5 0 0 1-7.6 4.7 8.38 8.38 0 0 1-3.8-.9L3 21l1.9-5.7a8.38 8.38 0 0 1-.9-3.8 8.5 8.5 0 0 1 4.7-7.6 8.38 8.38 0 0 1 3.8-.9h.5a8.48 8.48 0 0 1 8 8v.5z" />
        </svg>
      </button>
    </div>
  );
}
