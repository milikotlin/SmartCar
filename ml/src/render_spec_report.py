"""Renders docs/SPEC_MODELS.md from ml/spec_model1_results.json, ml/spec_model2_results.json and the model cards (numbers copied by code, never by hand).

Run: ml/.venv/Scripts/python.exe -I -X utf8 ml/src/render_spec_report.py
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from kaggle_sources import KAGGLE  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
r1 = json.loads((ROOT / "ml" / "spec_model1_results.json").read_text(encoding="utf-8"))
r2 = json.loads((ROOT / "ml" / "spec_model2_results.json").read_text(encoding="utf-8"))
ref = json.loads((ROOT / "backend" / "app" / "ml" / "artifacts" / "model2" / "model2_reference.json").read_text(encoding="utf-8"))
km = lambda x: f"{x:,.0f}"


def m1_tables() -> str:
    e1, e2 = r1["experiment_1_encoding"], r1["experiment_2_algorithms"]
    t = ["| Make/Model encoding (XGBoost held fixed) | CV RMSE (km) | CV MAE (km) |", "|---|---|---|"]
    t += [f"| {k.title()} Encoding{' (chosen)' if k == e1['chosen'] else ''} | {km(v['cv_rmse'])} | {km(v['cv_mae'])} |" for k, v in e1["scores"].items()]
    t += ["", "| Algorithm | CV RMSE (km) | CV MAE (km) | Held-out RMSE | Held-out MAE | Held-out R2 |", "|---|---|---|---|---|---|"]
    t += [f"| {k}{' (chosen)' if k == e2['chosen'] else ''} | {km(v['cv_rmse'])} | {km(v['cv_mae'])} | {km(v['test_rmse'])} | {km(v['test_mae'])} | {v['test_r2']:.3f} |" for k, v in e2["scores"].items()]
    return "\n".join(t)


def m2_table(part: str) -> str:
    p = r2[part]
    t = ["| Pipeline | CV Recall (guarded) | Test ROC-AUC | PR-AUC | Recall | Precision | F1 | Flagged share |", "|---|---|---|---|---|---|---|---|"]
    for k, v in p["pipelines"].items():
        s = v["test"]
        cv = f"{v['cv_guarded_recall']:.3f}" if "cv_guarded_recall" in v else "-"
        t.append(f"| {k}{' (chosen)' if k == p['chosen'] else ''} | {cv} | {s['roc_auc']:.3f} | {s['pr_auc']:.3f} | {s['recall']:.3f} | {s['precision']:.3f} | {s['f1']:.3f} | {s['flagged_share']:.2f} |")
    lv = p["levels"]
    t += ["", f"Base rate (training): {p['base_rate_train']:.3f}. Levels: {lv['rule']}; cut probabilities {lv['cut_probabilities'][0]:.3f} / {lv['cut_probabilities'][1]:.3f}; "
              f"share with the target in the held-out part by level (Low / Moderate / High): " + " / ".join(f"{x:.1%}" if x is not None else "-" for x in lv["test_rate_by_level"]) + "."]
    return "\n".join(t)


def single_auc(d: dict) -> str:
    return ", ".join(f"{k} {v:.3f}" for k, v in d.items())


ext = r2["external_check_uk_mot"]
used = {**r1.get("kaggle_sources", {}), **r2.get("kaggle_sources", {})}
support = ", ".join(f"{k.replace('lpg_cng', 'LPG/CNG')} older than {v} years" for k, v in r1["support_max_age"].items())
uk = {(r["variant"], r["system"]): r["UK cross-fitted AUC, standardised 12 months"] for r in ref["interval_standardisation_check"] if r["variant"] == "cold"}
cal = r1.get("calibration", {})
md = f"""# The two models exactly as Smart_Car_Models.pdf specifies

Generated by `ml/src/render_spec_report.py` from `ml/spec_model1_results.json`, `ml/spec_model2_results.json` and the model cards. Training scripts:
`ml/src/spec_model1.py`, `ml/src/spec_model2.py`. The datasets are pulled from Kaggle with `kagglehub`, with the handles of SmartCar_Data.pdf (`ml/src/kaggle_sources.py`).

## Data sources (Kaggle)

| Dataset | Source used |
|---|---|
""" + "\n".join(f"| {k} | {used.get(k, 'kagglehub: ' + KAGGLE[k][0])} |" for k in KAGGLE) + f"""

Dataset 1 (Logistics) answers 403 to anonymous Kaggle requests: it needs Kaggle credentials (`kagglehub.login()`, or `KAGGLE_USERNAME` / `KAGGLE_KEY`). Without them the
copy downloaded from the same Kaggle page on 2026-11-17 is used and the training log says so.

## Model 1: odometer regression

**As specified:** Datasets 7 (backbone), 8 (adds Owner_Type) and 3 (Cardekho), schema alignment ("CC" removed, UK miles converted to km, one fuel vocabulary, `pd.concat`);
One-Hot Encoding for fuel, transmission and owner type; a cross-validated comparison of Target and Frequency Encoding for Make/Model; KNN imputer with K=5;
Linear and Ridge regression (with StandardScaler or MinMaxScaler) against Random Forest and XGBoost; the final model chosen purely by RMSE and MAE.
Rows: {r1['rows']:,} ({', '.join(f'{k} {v:,}' for k, v in r1['rows_by_dataset'].items())}); {r1['make_model_categories']:,} make/model categories.

{m1_tables()}

**Chosen:** {r1['experiment_2_algorithms']['chosen']} with {r1['experiment_1_encoding']['chosen']} encoding, refitted on all rows. The indicative 80% range covers
{r1['interval_80pct_heldout_coverage']:.1%} of held-out vehicles.

**At run time** the features come from official sources: age and fuel from the registry, engine size and transmission from the Ministry of Transport model table
(WLTP, joined by manufacturer code, model code and year; {r1.get('registry_sample_with_official_engine_data', 0):.0%} of a random registry sample found), the number of
owners from the ownership history (one row per ownership; "Unknown" for cars older than that table), make and model from the registry. Missing values: the KNN imputer.

**Found while implementing:** Dataset 8 `Owner_Type` is the *number of owners* (First / Second / Third / Fourth & Above), not private / leasing / company as the PDF says;
it is used as such.

**Added on top of the PDF (documented):** the CBS calibration to the official Israeli level (age band x ownership, CBS Publication 1923; error on the held-out joint
cells: {cal.get('joint_cell_mean_abs_pct_error', float('nan')):.1f}%), the indicative range, and the low-reliability flags (electric vehicles; {support};
more than 40,000 km a year, in which case the official CBS average for that age and ownership is shown instead). Without the calibration the estimates would sit at the level of UK and Indian listings, about half the official Israeli usage.

## Model 2: predictive maintenance classifier

**As specified:** Dataset 1 (Logistics) for combustion vehicles; Dataset 4 not used raw but aggregated into the failure distribution (engine, brakes, battery) by mileage group
and joined to Dataset 1; a dedicated Dataset 5 model for electric and hybrid vehicles, used by the API only for them; every sensor column dropped; Vehicle_Age,
Days_Since_Last_Maintenance and a Brand_Reliability_Index; the mileage predicted by Model 1; SMOTE against scale_pos_weight; XGBoost against Logistic Regression; tuning that
maximises Recall.

**Decisions forced by the data:**
* Dataset 1 rows used: {r2['dataset1']['rows']:,} ({', '.join(f'{k} {v:,}' for k, v in r2['dataset1']['by_file'].items())}). Not used: {r2['dataset1']['excluded_file']}.
* Leakage removed: Anomalies_Detected (a sensor anomaly flag that is zero whenever the target is zero), Predictive_Score (a model output), Maintenance_Cost (the cost of the
  maintenance the target describes).
* Dataset 4 has no vehicle-age column: the distribution is grouped by mileage only ({r2['dataset4_aggregation']['note']}).
* Brand_Reliability_Index: none of the Kaggle datasets measures brand reliability, so it is computed from real inspection outcomes: {r2['brand_reliability_index']['method']}.
* Recall alone is maximised by flagging every vehicle; the tuning maximises Recall among models whose precision is above the base rate.
* Monotone constraints (added): more days since the last maintenance and more past failures never lower the score. Without them the model learned an artefact of
  mixing the two Dataset 1 generators (failure counts of 2 or more exist only in the file with the lower failure rate, so "more failures" lowered the risk). Cost on
  the held-out Dataset 1: about 0.001 ROC-AUC; on real UK inspections the model improved slightly (0.575 -> 0.585).
* Run-time inputs: age (registry); mileage = the value reported by the user or a recorded odometer if any, otherwise the Model 1 estimate; days since the last
  maintenance and its type from the service log; failure history = recorded inspection results with a defect. Unknown inputs take the training median, and the API lists them.

**How informative each input is on its own (ROC-AUC on Dataset 1, 0.5 = none):** {single_auc(r2['dataset1']['single_feature_auc'])}.

### Combustion vehicles (Dataset 1)

{m2_table('ice')}

### Electric and hybrid vehicles (Dataset 5)

Single-input ROC-AUC: {single_auc(r2['ev_dataset5']['single_feature_auc'])}.

{m2_table('ev')}

## Comparison with the model trained on real inspection outcomes

The dashboard shows Model 2 (above) as the main risk panel and keeps the model trained on real UK MOT inspections (validated on Dutch RDW inspections) as a comparison panel.

| Model | Data it is tested on | ROC-AUC |
|---|---|---|
| Model 2 (PDF), combustion | held-out Dataset 1 (synthetic labels) | {r2['ice']['pipelines'][r2['ice']['chosen']]['test']['roc_auc']:.3f} |
| Model 2 (PDF), electric / hybrid | held-out Dataset 5 (synthetic labels) | {r2['ev']['pipelines'][r2['ev']['chosen']]['test']['roc_auc']:.3f} |
| Model 2 (PDF), combustion | **real** UK MOT outcomes ({ext['pairs']:,} pairs; inputs: {ext['inputs']}) | {ext['spec_model2_auc']:.3f} |
| Age only (baseline) | the same real UK MOT outcomes | {ext['age_only_auc']:.3f} |
| Comparison model, brakes / electrical / engine | real UK MOT outcomes, out of sample | {uk.get(('cold', 'brakes'), float('nan')):.3f} / {uk.get(('cold', 'electrical'), float('nan')):.3f} / {uk.get(('cold', 'engine_emissions'), float('nan')):.3f} |

**Reading:** a score on synthetic data measures how well the model learned the dataset's own rules; the rows on real inspections measure how well it ranks real vehicles.
This is why Model 2 is shown as three relative levels, never as a percentage, and why the comparison panel stays on the dashboard.
"""
(ROOT / "docs" / "SPEC_MODELS.md").write_text(md, encoding="utf-8")
print("written docs/SPEC_MODELS.md")
